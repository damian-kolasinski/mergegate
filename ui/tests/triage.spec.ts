// The review part of F12: files the operator's rules trust fold into a group
// of their own, count as viewed, and leave the inbox's review figure.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { expect, type Hub, test } from "./hub";

const RULES = `[[rule]]
id = "R1"
tier = "trusted"
path = "**/*.lock"
reason = "regenerated by the package manager"
`;

/** Writes the project's rules.toml where the hub reads it. */
function rules(hub: Hub, project: string, text: string) {
  const dir = join(hub.root, "home", "projects", project);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "rules.toml"), text);
}

/** app#1 changes `src/main.rs` and the trusted `Cargo.lock`. */
function submitChange(hub: Hub) {
  const app = hub.project("app");
  rules(hub, "app", RULES);
  app.submit("deps", "Bump the parser", {
    "src/main.rs": "fn main() {}\n",
    "Cargo.lock": "version = 4\nparser = 2\nlexer = 1\n",
  });
}

test("f12 trusted files fold into a group of their own", async ({
  page,
  hub,
}) => {
  submitChange(hub);
  await page.goto(`${hub.url}#/items/app%231`);

  const screen = page.getByRole("region", { name: "app#1" });
  const files = screen.getByRole("navigation", { name: "Files" });
  await expect(files.getByRole("listitem")).toHaveText([/^src\/main\.rs/]);
  // Counted as viewed, so only the file to review is left.
  await expect(screen).toContainText("1/2 viewed");
  const diff = screen.getByRole("region", { name: "Diff" });
  await expect(diff.getByText("fn main() {}", { exact: true })).toBeVisible();
  await expect(diff.getByText("parser = 2", { exact: true })).toHaveCount(0);

  const group = files.getByRole("button", { name: "Trusted (1)" });
  await expect(group).toHaveAttribute("aria-expanded", "false");
  await group.click();
  await expect(group).toHaveAttribute("aria-expanded", "true");
  const trusted = files.getByRole("list", { name: "Trusted files" });
  await expect(trusted.getByRole("listitem")).toHaveText([
    /^Cargo\.lock\s*trusted by R1: `\*\*\/\*\.lock` — regenerated by the package manager\s*\+3$/,
  ]);
  const mark = trusted.getByRole("checkbox", { name: "Viewed Cargo.lock" });
  await expect(mark).toBeChecked();
  await expect(mark).toBeDisabled();
  // Open, its diff shows after the files to review.
  await expect(diff.getByText("parser = 2", { exact: true })).toBeVisible();
  const current = files.locator("li[aria-current=true]");
  await page.keyboard.press("n");
  await expect(current).toContainText("Cargo.lock");

  // Closing it takes the current file back to those still shown.
  await group.click();
  await expect(trusted).toHaveCount(0);
  await expect(current).toContainText("src/main.rs");
  await expect(diff.getByText("parser = 2", { exact: true })).toHaveCount(0);
});

test("f12 v skips trusted files", async ({ page, hub }) => {
  submitChange(hub);
  await page.goto(`${hub.url}#/items/app%231`);

  const screen = page.getByRole("region", { name: "app#1" });
  await expect(screen).toContainText("1/2 viewed");
  await page.keyboard.press("v");
  await expect(screen).toContainText("2/2 viewed");
  // Marking the last file to review leaves the trusted one out of reach.
  const current = screen
    .getByRole("navigation", { name: "Files" })
    .locator("li[aria-current=true]");
  await expect(current).toContainText("src/main.rs");
});

test("f12 the inbox counts the lines to review", async ({ page, hub }) => {
  submitChange(hub);
  const plain = hub.project("web");
  plain.submit("copy", "Fix the copy", { "index.html": "<p>hi</p>\n" });
  await page.goto(hub.url);

  const rows = page
    .getByRole("region", { name: "Needs you" })
    .getByRole("listitem");
  await expect(rows.filter({ hasText: "app#1" })).toContainText("1 to review");
  await expect(rows.filter({ hasText: "app#1" })).toContainText("+4");
  // Nothing trusted, nothing to set apart.
  await expect(rows.filter({ hasText: "web#1" })).not.toContainText(
    "to review",
  );
});

test("f12 a changed .gitattributes stays in review", async ({ page, hub }) => {
  const app = hub.project("app");
  rules(
    hub,
    "app",
    `[[rule]]\nid = "R1"\ntier = "trusted"\npath = "**"\nreason = "everything"\n`,
  );
  app.submit("attrs", "Mark the bundle generated", {
    ".gitattributes": "dist/** linguist-generated\n",
    "notes.txt": "hello\n",
  });
  await page.goto(`${hub.url}#/items/app%231`);

  const files = page.getByRole("navigation", { name: "Files" });
  await expect(files.getByRole("listitem")).toHaveText([
    /^\.gitattributes\s*kept in review: it can mark files generated/,
  ]);
  await expect(
    files.getByRole("button", { name: "Trusted (1)" }),
  ).toBeVisible();
});
