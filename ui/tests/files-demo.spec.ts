// Screenshots of the file list: a Tuist app's change grouped by its
// target groups and a Cargo workspace's by its crates, each with a judge's
// scores and one file's note open, in light and dark. Skipped unless
// MG_SHOTS_DIR names where to write them:
//
//   MG_SHOTS_DIR=$(mktemp -d) pnpm --dir ui e2e files-demo --project chromium

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import type { Page } from "@playwright/test";
import { expect, Hub, type Project, test } from "./hub";
import { FakeJev } from "./jev";

const out = process.env.MG_SHOTS_DIR ?? "";

test.skip(!out, "MG_SHOTS_DIR is unset");

/** `n` lines of Swift, so each file's counts differ. */
const swift = (name: string, n: number) =>
  `struct ${name} {\n${Array.from({ length: n }, (_, i) => `  let field${i} = ${i}\n`).join("")}}\n`;

const rust = (name: string, n: number) =>
  `pub fn ${name}() {\n${Array.from({ length: n }, (_, i) => `    step(${i});\n`).join("")}}\n`;

const KC = "Products/Messenger";

const TUIST_GUIDE = `Lets a group's admin rename it.

## Files

- \`${KC}/ChatGroups/ChatGroups/Scenes/Rename/RenameGroupViewModel.swift\` — validates and saves the name, start here
- \`${KC}/ChatGroups/ChatGroups/Scenes/Rename/RenameGroupView.swift\` — the new screen
- \`${KC}/ChatGroups/ChatGroupsInterface/ChatGroupsRoute.swift\` — the route other modules open it by
- \`${KC}/ChatGroups/ChatGroups/Services/GroupService.swift\` — the rename call
- \`${KC}/Profile/Profile/Header/GroupHeaderView.swift\` — shows the new name
- \`${KC}/Shared/Localization/Localizable.strings\` — copy
`;

const CARGO_GUIDE = `Keeps sessions alive across hub restarts.

## Files

- \`crates/core/src/session/store.rs\` — the new port, start here
- \`crates/store-sqlite/src/sessions.rs\` — its SQLite adapter
- \`crates/hub/src/serve.rs\` — wires the store in
- \`crates/hub/src/routes/session.rs\` — reads it per request
`;

async function shoot(page: Page, name: string, row: string) {
  const files = page.getByRole("navigation", { name: "Files" });
  await expect(files).toBeVisible();
  for (const scheme of ["light", "dark"] as const) {
    await page.emulateMedia({ colorScheme: scheme });
    await page.mouse.move(900, 600);
    await page.screenshot({
      path: join(out, `${name}-${scheme}.png`),
      animations: "disabled",
    });
    await files.getByRole("button", { name: `Why ${row} is here` }).click();
    const note = page.getByRole("dialog", { name: "Why this file" });
    await expect(note).toBeVisible();
    await page.screenshot({
      path: join(out, `${name}-note-${scheme}.png`),
      animations: "disabled",
    });
    await page.keyboard.press("Escape");
    await expect(note).toHaveCount(0);
  }
}

function submit(hub: Hub, app: Project, guide: string) {
  const path = join(hub.root, "guide.md");
  writeFileSync(path, guide);
  hub.mg(["submit", "--guide", path], app.dir);
}

