// Approving rules: a rule that would hide files waits in the UI
// until the operator approves it, after seeing what it would have hidden.

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { expect, test } from "./hub";

test("f12 the operator approves a proposed trusted rule", async ({
  page,
  hub,
}) => {
  const app = hub.project("app");
  app.submit("deps", "Bump the parser", {
    "src/main.rs": "fn main() {}\n",
    "Cargo.lock": "version = 4\n",
  });
  hub.mg(
    [
      "rules",
      "propose",
      "--tier",
      "trusted",
      "--path",
      "**/*.lock",
      "--reason",
      "regenerated by the package manager",
    ],
    app.dir,
  );
  await page.goto(hub.url);

  const badge = page.getByRole("list", { name: "Rule changes" });
  await expect(badge).toHaveText("app · 1 rule change to approve");
  await badge.getByRole("link").click();

  const screen = page.getByRole("region", { name: "app rules" });
  const waiting = screen.getByRole("region", { name: "Waiting for you" });
  const proposal = waiting.getByRole("listitem", { name: "Proposed R1" });
  await expect(proposal).toContainText(
    "R1trusted`**/*.lock`regenerated by the package manager",
  );
  await expect(proposal).toContainText(
    "Would have hidden 1 file in 1 of 1 recent item.",
  );
  await expect(
    proposal.getByRole("list", { name: "Files it would have hidden" }),
  ).toContainText("app#1Cargo.lockBump the parser · by R1");

  await proposal.getByRole("button", { name: "Approve" }).click();
  await expect(waiting).toHaveCount(0);
  await expect(
    screen.getByRole("list", { name: "Applied rules" }).getByRole("listitem"),
  ).toHaveText(["R1trusted`**/*.lock`regenerated by the package manager"]);

  // The open item re-triages, and the inbox has nothing left to approve.
  await page.goto(`${hub.url}#/items/app%231`);
  await expect(page.getByRole("button", { name: "Trusted (1)" })).toBeVisible();
  await page.goto(hub.url);
  await expect(page.getByRole("list", { name: "Rule changes" })).toHaveCount(0);
});

test("f12 rejecting a held edit writes the applied rules back", async ({
  page,
  hub,
}) => {
  hub.project("app");
  await page.goto(`${hub.url}#/projects/app/rules`);
  const screen = page.getByRole("region", { name: "app rules" });
  await expect(screen).toContainText("No rules, so every file is reviewed.");

  // The hub watches the file, so the edit shows up without a reload.
  const dir = join(hub.root, "home", "projects", "app");
  mkdirSync(dir, { recursive: true });
  const file = join(dir, "rules.toml");
  const edit = `[[rule]]\nid = "R1"\ntier = "trusted"\npath = "**"\nreason = "everything"\n`;
  writeFileSync(file, edit);
  const held = screen
    .getByRole("region", { name: "Waiting for you" })
    .getByRole("listitem", { name: "Edit to the rules file" });
  await expect(held).toContainText("R1trusted`**`everything");

  await held.getByRole("button", { name: "Reject" }).click();
  await expect(held).toContainText(
    "Overwrite rules.toml with the 0 applied rules?",
  );
  await held.getByRole("button", { name: "Overwrite" }).click();
  await expect(held).toHaveCount(0);
  await expect(screen).toContainText("No rules, so every file is reviewed.");
});
