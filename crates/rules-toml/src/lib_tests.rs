use super::*;

fn app() -> ProjectName {
    ProjectName::parse("app").unwrap()
}

#[test]
fn reads_rules_in_file_order() {
    let rules = parse(
        r#"
# Lockfiles change with every dependency bump.
[[rule]]
id = "R2"
tier = "trusted"
path = "**/*.lock"
kind = "generated"
max_lines = 200
diff_matches = '^\s*version'
reason = "regenerated by cargo"

[[rule]]
id = "R1"
tier = "review"
path = "src/auth/**"
reason = "security-sensitive"
"#,
    )
    .unwrap();
    assert_eq!(
        rules,
        [
            Rule {
                id: RuleId::new(2),
                tier: Tier::Trusted,
                path: Some("**/*.lock".into()),
                kind: Some(Kind::Generated),
                max_lines: Some(200),
                diff_matches: Some(r"^\s*version".into()),
                reason: "regenerated by cargo".into(),
            },
            Rule {
                id: RuleId::new(1),
                tier: Tier::Review,
                path: Some("src/auth/**".into()),
                kind: None,
                max_lines: None,
                diff_matches: None,
                reason: "security-sensitive".into(),
            },
        ]
    );
    assert_eq!(parse("").unwrap(), []);
}

#[test]
fn names_the_line_of_a_mistake() {
    let rule = |body: &str| format!("[[rule]]\nid = \"R1\"\nreason = \"x\"\n{body}\n");
    for (text, error) in [
        (
            rule("tier = \"hidden\""),
            "line 4: unknown tier \"hidden\", expected review or trusted",
        ),
        (
            rule("tier = \"trusted\"\nkind = \"new\""),
            "line 5: unknown kind \"new\", expected one of added, deleted, renamed, modified, generated",
        ),
        (
            rule("tier = \"trusted\"\npaths = \"*\""),
            "line 5: unknown field `paths`",
        ),
        (
            rule("tier = \"trusted\"\nmax_lines = -1"),
            "line 5: invalid value",
        ),
        (
            "[[rule]]\nid = \"r1\"".into(),
            "line 2: \"r1\" isn't an ID like R1",
        ),
        ("[[rule]\n".into(), "line 1: unclosed array table"),
    ] {
        let got = parse(&text).unwrap_err();
        assert!(got.starts_with(error), "{got:?} for\n{text}");
    }
}

#[test]
fn a_missing_file_holds_no_rules() {
    let dir = tempfile::tempdir().unwrap();
    let file = RulesToml::new(dir.path().to_owned());
    assert_eq!(file.read(&app()).unwrap(), []);
    std::fs::create_dir_all(dir.path().join("app/rules.toml")).unwrap();
    assert!(matches!(
        file.read(&app()),
        Err(RulesFileError::Unreadable(_))
    ));
    assert_eq!(
        file.location(&app()),
        dir.path().join("app/rules.toml").display().to_string()
    );
}
