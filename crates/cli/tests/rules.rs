//! Triage (F12): the operator's rules.toml sorts each submitted file into
//! review or trusted, the hub serves the tiers with their reasons, and the
//! inbox counts only the files left to review.

use std::fs;

use serde_json::{Value, json};
use testkit::{Env, Reply, TestRepo, http_reply};

fn env() -> Env {
    Env::new(env!("CARGO_BIN_EXE_mg"))
}

fn get(env: &Env, path: &str) -> Reply {
    let addr = env.hub_addr();
    http_reply(
        &addr,
        &format!("GET {path} HTTP/1.1\r\nHost: {addr}\r\nConnection: close\r\n\r\n"),
    )
}

fn json_of(reply: &Reply) -> Value {
    serde_json::from_str(&reply.body).unwrap_or_else(|e| panic!("{e}: {}", reply.body))
}

const RULES: &str = r#"
[[rule]]
id = "R1"
tier = "review"
path = "src/auth/**"
reason = "security-sensitive"

[[rule]]
id = "R2"
tier = "trusted"
path = "**/*.lock"
reason = "regenerated by cargo"

[[rule]]
id = "R3"
tier = "trusted"
kind = "generated"
reason = "built from src"
"#;

/// The project `app`, registered, with `dist/**` generated on `main`.
fn project(env: &Env) -> TestRepo {
    env.start_hub();
    let repo = TestRepo::new("app");
    repo.commit_files(
        "Base",
        &[(".gitattributes", "dist/** linguist-generated\n")],
    );
    env.mg_at(repo.root(), &["--json", "project", "add"])
        .assert_code(0);
    env.mg_at(repo.root(), &["--json", "init"]).assert_code(0);
    repo
}

fn write_rules(env: &Env, text: &str) {
    let dir = env.home().join("projects").join("app");
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("rules.toml"), text).unwrap();
}

fn submit(env: &Env, repo: &TestRepo, files: &[(&str, &str)]) {
    repo.git(["switch", "--quiet", "-c", "feature"]);
    repo.commit_files("Bump the parser", files);
    env.mg_at(repo.root(), &["--json", "submit"]).assert_code(0);
}

/// Each file's path with its triage, in the diff's order.
fn triage(env: &Env) -> Vec<Value> {
    let diff = json_of(&get(env, "/api/items/app%231"));
    diff["files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|file| {
            json!({
                "path": file["path"],
                "generated": file["generated"],
                "tier": file["tier"],
                "rule": file["rule"],
                "why": file["why"],
            })
        })
        .collect()
}

#[test]
fn f12_rules_sort_files_into_review_and_trusted() {
    let env = env();
    let repo = project(&env);
    write_rules(&env, RULES);
    submit(
        &env,
        &repo,
        &[
            ("Cargo.lock", "a\nb\nc\n"),
            ("dist/app.js", "x\ny\n"),
            ("src/auth/login.rs", "fn login() {}\n"),
            ("src/main.rs", "fn main() {}\n"),
        ],
    );

    assert_eq!(
        triage(&env),
        [
            json!({
                "path": "Cargo.lock", "generated": false, "tier": "trusted",
                "rule": "R2", "why": "`**/*.lock` — regenerated by cargo",
            }),
            json!({
                "path": "dist/app.js", "generated": true, "tier": "trusted",
                "rule": "R3", "why": "generated — built from src",
            }),
            json!({
                "path": "src/auth/login.rs", "generated": false, "tier": "review",
                "rule": "R1", "why": "`src/auth/**` — security-sensitive",
            }),
            json!({
                "path": "src/main.rs", "generated": false, "tier": "review",
                "rule": null, "why": null,
            }),
        ]
    );
    let inbox = env.mg(&["--json", "inbox"]).assert_code(0).json();
    let item = &inbox["needs_you"][0];
    assert_eq!(
        [&item["files"], &item["review_files"]],
        [&json!(4), &json!(2)]
    );
    let text = env.mg(&["inbox"]).assert_code(0).stdout;
    assert!(text.contains("2 of 4 files to review, +7 -0"), "{text}");
}

#[test]
fn f12_without_rules_every_file_is_reviewed() {
    let env = env();
    let repo = project(&env);
    submit(
        &env,
        &repo,
        &[("Cargo.lock", "a\n"), ("dist/app.js", "x\n")],
    );

    let tiers: Vec<_> = triage(&env).iter().map(|f| f["tier"].clone()).collect();
    assert_eq!(tiers, [json!("review"), json!("review")]);
    let text = env.mg(&["inbox"]).assert_code(0).stdout;
    assert!(!text.contains("to review"), "{text}");

    // Open items follow an edit without a new submit.
    write_rules(&env, RULES);
    env.mg(&["rules", "list", "app"]).assert_code(0);
    let tiers: Vec<_> = triage(&env).iter().map(|f| f["tier"].clone()).collect();
    assert_eq!(tiers, [json!("trusted"), json!("trusted")]);
    let item = &env.mg(&["--json", "inbox"]).assert_code(0).json()["needs_you"][0];
    assert_eq!(item["review_files"], 0);
}

#[test]
fn f12_a_changed_gitattributes_stays_in_review() {
    let env = env();
    let repo = project(&env);
    write_rules(
        &env,
        "[[rule]]\nid = \"R1\"\ntier = \"trusted\"\npath = \"**\"\nreason = \"everything\"\n",
    );
    submit(
        &env,
        &repo,
        &[
            (".gitattributes", "*.js linguist-generated\n"),
            ("a.js", "x\n"),
        ],
    );

    let files = triage(&env);
    assert_eq!(
        files[0],
        json!({
            "path": ".gitattributes", "generated": false, "tier": "review",
            "rule": null, "why": "it can mark files generated, which rules match on",
        })
    );
    // Read from the base, which doesn't mark it generated yet.
    assert_eq!(
        [&files[1]["tier"], &files[1]["generated"]],
        [&json!("trusted"), &json!(false)]
    );
}

#[test]
fn f12_code_moved_into_a_generated_directory_stays_in_review() {
    let env = env();
    let repo = project(&env);
    write_rules(&env, RULES);
    repo.commit_files("Add core", &[("lib/core.rs", "fn core() {}\n")]);
    repo.git(["switch", "--quiet", "-c", "feature"]);
    fs::create_dir(repo.root().join("dist")).unwrap();
    repo.git(["mv", "lib/core.rs", "dist/core.rs"]);
    repo.commit("Move core");
    env.mg_at(repo.root(), &["--json", "submit"]).assert_code(0);

    let files = triage(&env);
    assert_eq!(
        [&files[0]["path"], &files[0]["generated"], &files[0]["tier"]],
        [&json!("dist/core.rs"), &json!(false), &json!("review")]
    );
}

#[test]
fn f12_rules_list_shows_the_applied_rules() {
    let env = env();
    let repo = project(&env);
    write_rules(&env, RULES);

    let listed = env
        .mg_at(repo.root(), &["--json", "rules", "list"])
        .assert_code(0)
        .json();
    assert_eq!(listed["project"], "app");
    assert_eq!(listed["error"], Value::Null);
    let ids: Vec<_> = listed["rules"]
        .as_array()
        .unwrap()
        .iter()
        .map(|r| [r["id"].clone(), r["tier"].clone(), r["summary"].clone()])
        .collect();
    assert_eq!(
        ids,
        [
            [json!("R1"), json!("review"), json!("`src/auth/**`")],
            [json!("R2"), json!("trusted"), json!("`**/*.lock`")],
            [json!("R3"), json!("trusted"), json!("generated")],
        ]
    );
    let text = env.mg(&["rules", "list", "app"]).assert_code(0).stdout;
    assert!(
        text.contains("  R2  trusted  `**/*.lock` — regenerated by cargo"),
        "{text}"
    );
}

#[test]
fn f12_a_broken_rules_file_keeps_the_last_good_rules() {
    let env = env();
    let repo = project(&env);
    write_rules(&env, RULES);
    env.mg(&["rules", "list", "app"]).assert_code(0);
    write_rules(&env, "[[rule]]\nid = \"R4\"\ntier = \"hidden\"\n");
    submit(&env, &repo, &[("Cargo.lock", "a\n")]);

    let listed = env
        .mg(&["--json", "rules", "list", "app"])
        .assert_code(0)
        .json();
    let error = listed["error"].as_str().unwrap();
    assert!(error.starts_with("line 3: "), "{error}");
    assert_eq!(listed["rules"].as_array().unwrap().len(), 3);
    assert_eq!(triage(&env)[0]["rule"], "R2");
    let text = env.mg(&["rules", "list", "app"]).assert_code(0).stdout;
    assert!(text.contains("can't be used"), "{text}");
}
