//! F12's ranking and promotion: a project's judge scores each submitted
//! revision in the background, its scores rank the files to review, and a
//! confident one pulls a rule-trusted file back into review.

use std::fs;
use std::time::{Duration, Instant};

use serde_json::{Value, json};
use testkit::{Env, FakeJev, TestRepo, http_reply};

/// A hub pointed at `jev`, never at TypeSafe's API, whatever the machine's
/// environment holds.
fn env(jev: &FakeJev) -> Env {
    Env::new(env!("CARGO_BIN_EXE_mg")).with_vars(jev.env())
}

fn item(env: &Env) -> Value {
    let addr = env.hub_addr();
    let reply = http_reply(
        &addr,
        &format!("GET /api/items/app%231 HTTP/1.1\r\nHost: {addr}\r\nConnection: close\r\n\r\n"),
    );
    assert_eq!(reply.status, 200, "{}", reply.body);
    serde_json::from_str(&reply.body).unwrap()
}

/// The item once `done` holds of it, as the judge runs in the background.
#[track_caller]
fn item_when(env: &Env, done: impl Fn(&Value) -> bool) -> Value {
    let deadline = Instant::now() + Duration::from_secs(20);
    loop {
        let item = item(env);
        if done(&item) {
            return item;
        }
        assert!(Instant::now() < deadline, "never happened: {item:#}");
        std::thread::sleep(Duration::from_millis(50));
    }
}

fn judged(item: &Value) -> bool {
    item["files"]
        .as_array()
        .unwrap()
        .iter()
        .any(|f| !f["importance"].is_null())
}

/// The judge show once `done` holds of it.
#[track_caller]
fn show_when(env: &Env, done: impl Fn(&Value) -> bool) -> Value {
    let deadline = Instant::now() + Duration::from_secs(20);
    loop {
        let show = env
            .mg(&["--json", "judge", "show", "app"])
            .assert_code(0)
            .json();
        if done(&show) {
            return show;
        }
        assert!(Instant::now() < deadline, "never happened: {show:#}");
        std::thread::sleep(Duration::from_millis(50));
    }
}

/// Each file as the review screen ranks it.
fn ranked(item: &Value) -> Vec<Value> {
    item["files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| {
            json!({
                "path": f["path"],
                "tier": f["tier"],
                "importance": f["importance"],
                "raised": f["raised"],
                "promoted": f["promoted"],
            })
        })
        .collect()
}

const RULES: &str = r#"
[[rule]]
id = "R1"
tier = "trusted"
path = "**/*.lock"
reason = "regenerated by cargo"

[[rule]]
id = "R2"
tier = "trusted"
path = "config/**"
reason = "settings only"
"#;

const GUIDE: &str = "Adds the login form.

## Files

- `src/a.rs` — the form
- `src/b.rs` — wiring
";

/// The project `app` with [`RULES`] applied, as the operator approved them.
fn project(env: &Env) -> TestRepo {
    env.start_hub();
    let repo = TestRepo::new("app");
    repo.commit_files("Base", &[("README.md", "app\n")]);
    env.mg_at(repo.root(), &["--json", "project", "add"])
        .assert_code(0);
    env.mg_at(repo.root(), &["--json", "init"]).assert_code(0);
    let dir = env.home().join("projects").join("app");
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("rules.toml"), RULES).unwrap();
    let addr = env.hub_addr();
    // Reading the rules picks up the file; trusted rules wait for approval.
    http_reply(
        &addr,
        &format!(
            "GET /api/projects/app/rules HTTP/1.1\r\nHost: {addr}\r\nConnection: close\r\n\r\n"
        ),
    );
    let reply = http_reply(
        &addr,
        &format!(
            "POST /api/projects/app/rules/edit/approve HTTP/1.1\r\nHost: {addr}\r\n\
             Connection: close\r\n{}: ui\r\nContent-Length: 0\r\n\r\n",
            api::CLIENT_HEADER,
        ),
    );
    assert_eq!(reply.status, 200, "{}", reply.body);
    repo
}

fn submit(env: &Env, repo: &TestRepo) {
    repo.git(["switch", "--quiet", "-c", "feature"]);
    repo.commit_files(
        "Add login",
        &[
            ("src/a.rs", "fn form() {}\n"),
            ("src/b.rs", "fn wire() {}\n"),
            ("src/c.rs", "fn check_password() {}\n"),
            ("Cargo.lock", "a\nb\n"),
            ("config/prod.toml", "auth = false\n"),
        ],
    );
    fs::write(repo.root().join("guide.md"), GUIDE).unwrap();
    env.mg_at(repo.root(), &["--json", "submit", "--guide", "guide.md"])
        .assert_code(0);
}

#[test]
fn f12_the_judge_ranks_files_and_promotes_a_trusted_one() {
    let jev = FakeJev::start();
    jev.score("src/a.rs", 3.0)
        .score("src/b.rs", 2.0)
        .score("src/c.rs", 9.0)
        .score("config/prod.toml", 7.0)
        .look("config/prod.toml", 0.95)
        .score("Cargo.lock", 0.0)
        .look("Cargo.lock", 0.5);
    let env = env(&jev);
    let repo = project(&env);
    let set = env
        .mg_at(repo.root(), &["--json", "judge", "set", "jev"])
        .assert_code(0)
        .json();
    assert_eq!(
        [
            &set["provider"],
            &set["model"],
            &set["threshold"],
            &set["order"]
        ],
        [
            &json!("jev"),
            &json!("jev-1.13.0"),
            &json!(0.8),
            &json!("guide")
        ]
    );
    submit(&env, &repo);

    let judged_item = item_when(&env, judged);
    assert_eq!(
        ranked(&judged_item),
        [
            // Scored high enough to go ahead of the guide's list.
            json!({ "path": "src/c.rs", "tier": "review", "importance": 100, "raised": true, "promoted": false }),
            json!({ "path": "src/a.rs", "tier": "review", "importance": 34, "raised": false, "promoted": false }),
            json!({ "path": "src/b.rs", "tier": "review", "importance": 23, "raised": false, "promoted": false }),
            json!({ "path": "config/prod.toml", "tier": "review", "importance": 78, "raised": false, "promoted": true }),
            json!({ "path": "Cargo.lock", "tier": "trusted", "importance": 1, "raised": false, "promoted": false }),
        ]
    );
    let promoted = &judged_item["files"][3];
    assert_eq!(
        [&promoted["rule"], &promoted["why"]],
        [&json!("R2"), &json!("`config/**` — settings only")],
        "a promoted file still names the rule that trusted it"
    );
    let inbox = env.mg(&["--json", "inbox"]).assert_code(0).json();
    assert_eq!(inbox["needs_you"][0]["review_files"], 4);

    // One call for the whole change, which it sees in full.
    let requests = jev.requests();
    assert_eq!(requests.len(), 1);
    assert_eq!(requests[0]["model"], "jev-1.13.0");
    let state = requests[0]["state"].as_str().unwrap();
    for part in [
        "Title: Add login",
        "Adds the login form.",
        "2. config/prod.toml (added, +1 -0, marked safe to skip by a rule)",
        "### File 5: src/c.rs",
    ] {
        assert!(state.contains(part), "{part:?} in:\n{state}");
    }

    // A threshold only changes what's promoted: nothing is judged again.
    env.mg(&[
        "--json",
        "judge",
        "set",
        "jev",
        "--threshold",
        "0.99",
        "--project",
        "app",
    ])
    .assert_code(0);
    let demoted = item_when(&env, |item| item["files"][3]["tier"] == "trusted");
    assert_eq!(demoted["files"][3]["path"], "Cargo.lock");
    let show = env
        .mg(&["--json", "judge", "show", "app"])
        .assert_code(0)
        .json();
    assert_eq!(
        [&show["waiting"], &show["problem"]],
        [&json!(0), &json!(null)]
    );
    assert_eq!(jev.requests().len(), 1);

    // Led by the judge, its scores place every file to review, the promoted
    // one too, and the guide only breaks ties: nothing is judged again.
    let set = env
        .mg(&[
            "--json",
            "judge",
            "set",
            "jev",
            "--order",
            "judge",
            "--project",
            "app",
        ])
        .assert_code(0)
        .json();
    assert_eq!(set["order"], "judge");
    let by_judge = item_when(&env, |item| item["files"][1]["path"] == "config/prod.toml");
    assert_eq!(
        ranked(&by_judge),
        [
            json!({ "path": "src/c.rs", "tier": "review", "importance": 100, "raised": false, "promoted": false }),
            json!({ "path": "config/prod.toml", "tier": "review", "importance": 78, "raised": false, "promoted": true }),
            json!({ "path": "src/a.rs", "tier": "review", "importance": 34, "raised": false, "promoted": false }),
            json!({ "path": "src/b.rs", "tier": "review", "importance": 23, "raised": false, "promoted": false }),
            json!({ "path": "Cargo.lock", "tier": "trusted", "importance": 1, "raised": false, "promoted": false }),
        ]
    );
    let text = env.mg(&["judge", "show", "app"]).assert_code(0).stdout;
    assert!(
        text.contains("its scores order the files to review; the guide breaks ties"),
        "{text}"
    );
    assert_eq!(jev.requests().len(), 1);

    // Without a judge, the guide and the heuristics rank alone.
    let text = env
        .mg_at(repo.root(), &["judge", "set", "none"])
        .assert_code(0)
        .stdout;
    assert!(text.contains("app has no judge"), "{text}");
    let paths: Vec<_> = item(&env)["files"]
        .as_array()
        .unwrap()
        .iter()
        .map(|f| f["path"].clone())
        .collect();
    assert_eq!(
        paths,
        [
            "src/a.rs",
            "src/b.rs",
            "src/c.rs",
            "Cargo.lock",
            "config/prod.toml"
        ]
    );
}

#[test]
fn f12_a_failing_judge_is_shown_and_retried_when_set_again() {
    let jev = FakeJev::start();
    // Busy through every retry of the first call.
    jev.busy(6);
    let env = env(&jev);
    let repo = project(&env);
    env.mg_at(repo.root(), &["--json", "judge", "set", "jev"])
        .assert_code(0);
    submit(&env, &repo);

    let show = show_when(&env, |show| {
        !show["failures"].as_array().unwrap().is_empty()
    });
    assert_eq!(
        show["failures"],
        json!([{ "item": "app#1", "revision": 1, "error": "Jev answered 529: overloaded" }])
    );
    assert_eq!(show["waiting"], 1);
    let text = env.mg(&["judge", "show", "app"]).assert_code(0).stdout;
    assert!(text.contains("failed on app#1 revision 1"), "{text}");
    assert!(
        text.contains("setting the judge again retries them"),
        "{text}"
    );
    assert!(!judged(&item(&env)), "the files keep the usual order");

    env.mg(&["--json", "judge", "set", "jev", "--project", "app"])
        .assert_code(0);
    item_when(&env, judged);
    let show = env
        .mg(&["--json", "judge", "show", "app"])
        .assert_code(0)
        .json();
    assert_eq!(
        [&show["waiting"], &show["failures"]],
        [&json!(0), &json!([])]
    );
}

#[test]
fn f12_jev_without_its_key_says_so() {
    let jev = FakeJev::start();
    let env = env(&jev);
    let repo = project(&env);
    // The hub reads the key from its own environment, so it starts without.
    env.mg(&["--json", "hub", "stop"]).assert_code(0);
    env.mg_with_env(
        &["--json", "hub", "start", "--port", "0"],
        &[("TYPESAFE_API_KEY", "")],
    )
    .assert_code(0);

    let show = env
        .mg_at(repo.root(), &["--json", "judge", "set", "jev"])
        .assert_code(0)
        .json();
    assert_eq!(
        show["problem"],
        "TYPESAFE_API_KEY isn't set in the hub's environment"
    );
    submit(&env, &repo);
    let show = show_when(&env, |show| {
        !show["failures"].as_array().unwrap().is_empty()
    });
    assert_eq!(
        show["failures"][0]["error"],
        "TYPESAFE_API_KEY isn't set in the hub's environment"
    );
    assert!(jev.requests().is_empty());
}

#[test]
fn f12_a_command_judges_from_the_projects_repo() {
    let jev = FakeJev::start();
    let env = env(&jev);
    let repo = project(&env);
    let seen = tempfile::tempdir().unwrap();
    let input = seen.path().join("input.json");
    // Run in the repo, so it can read more than the diff.
    let command = format!(
        "cat > '{}'; test -f README.md && printf '%s' \
         '{{\"files\": [{{\"path\": \"src/b.rs\", \"importance\": 90, \"reason\": \"wires the form in\"}}]}}'",
        input.display()
    );
    env.mg_at(
        repo.root(),
        &["--json", "judge", "set", "command", "--command", &command],
    )
    .assert_code(0);
    submit(&env, &repo);

    let item = item_when(&env, judged);
    let first = &item["files"][0];
    assert_eq!(
        [
            &first["path"],
            &first["importance"],
            &first["judge_reason"],
            &first["raised"]
        ],
        [
            &json!("src/b.rs"),
            &json!(90),
            &json!("wires the form in"),
            &json!(true)
        ]
    );
    let given: Value = serde_json::from_slice(&fs::read(&input).unwrap()).unwrap();
    assert_eq!(
        [&given["item"], &given["revision"], &given["title"]],
        [&json!("app#1"), &json!(1), &json!("Add login")]
    );
    let lock = given["files"]
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["path"] == "Cargo.lock")
        .unwrap();
    assert_eq!(
        lock,
        &json!({
            "path": "Cargo.lock", "old_path": null, "change": "added",
            "additions": 2, "deletions": 0, "tier": "trusted", "generated": false,
            "old_mode": null, "new_mode": "100644",
            "diff": "@@ -0,0 +1,2 @@\n+a\n+b\n",
        })
    );
}

#[test]
fn f12_a_failing_command_is_shown_by_what_it_said() {
    let jev = FakeJev::start();
    let env = env(&jev);
    let repo = project(&env);
    env.mg_at(
        repo.root(),
        &[
            "--json",
            "judge",
            "set",
            "command",
            "--command",
            "echo 'no model loaded' >&2; exit 3",
        ],
    )
    .assert_code(0);
    submit(&env, &repo);

    let show = show_when(&env, |show| {
        !show["failures"].as_array().unwrap().is_empty()
    });
    let error = show["failures"][0]["error"].as_str().unwrap();
    assert!(error.ends_with(": no model loaded"), "{error}");
}

#[test]
fn f12_judge_settings_are_checked() {
    let jev = FakeJev::start();
    let env = env(&jev);
    let repo = project(&env);
    for (args, message) in [
        (
            &["judge", "set", "command"][..],
            "the command judge needs --command",
        ),
        (
            &["judge", "set", "jev", "--threshold", "1.5"],
            "the threshold must be above 0 and at most 1, got 1.5",
        ),
        (
            &["judge", "set", "jev", "--command", "x"],
            "--command is only for the command judge",
        ),
        (
            &["judge", "set", "none", "--threshold", "0.5"],
            "none takes no options",
        ),
        (
            &["judge", "set", "none", "--order", "judge"],
            "none takes no options",
        ),
    ] {
        let mut args = args.to_vec();
        args.insert(0, "--json");
        let run = env.mg_at(repo.root(), &args);
        assert_ne!(run.code, 0, "{args:?}");
        let error = &run.json()["error"];
        assert_eq!(
            [&error["code"], &error["message"]],
            [&json!("invalid_judge"), &json!(message)],
            "{args:?}"
        );
    }
    let show = env
        .mg(&["--json", "judge", "show", "app"])
        .assert_code(0)
        .json();
    assert_eq!(show["provider"], "none");
    let run = env.mg(&["--json", "judge", "show", "nope"]);
    assert_eq!(run.json()["error"]["code"], "project_not_found");
}
