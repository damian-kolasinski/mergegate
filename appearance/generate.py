#!/usr/bin/env python3
"""Generate web tokens and feature-local native appearance from one palette."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
tokens = json.loads((ROOT / 'appearance/tokens.json').read_text())

def resolved(theme, key):
    value = tokens[theme].get(key, tokens['light'].get(key))
    if value.startswith('var('):
        return resolved(theme, value[6:-1])
    return value

def rgb(hex_color):
    return ', '.join(f'{label}: {int(hex_color[i:i+2], 16) / 255:.6f}' for label, i in zip(['red', 'green', 'blue'], [1, 3, 5]))

css = '/* Generated by appearance/generate.py; edit appearance/tokens.json. */\n'
for theme, values in tokens.items():
    body = ':root {\n' + ''.join(f'  --{k}: {v};\n' for k, v in values.items()) + '}\n'
    css += body if theme == 'light' else '\n@media (prefers-color-scheme: dark) {\n' + ''.join('  ' + line + '\n' for line in body.splitlines()) + '}\n'

swift = '''// Generated by appearance/generate.py. Compiled privately into each feature.
import SwiftUI
import UIKit

enum Appearance {
'''
for name,key in {'page':'background-page','surface':'background-subtle','border':'border-inactive','controlBorder':'border-strong','tintBrand':'background-tint-brand','tintSuccess':'background-tint-success','tintError':'background-tint-error','tintWarning':'background-tint-warning','tintNeutral':'background-tint-neutral','onTintWarning':'text-tint-warning','onTintNeutral':'text-tint-neutral','warning':'background-warning','onTintBrand':'text-tint-brand','onTintSuccess':'text-tint-success','onTintError':'text-tint-error','primary':'text-primary','secondary':'text-secondary','brand':'background-brand','onFill':'text-on-fill','error':'text-error','added':'text-added','removed':'text-removed'}.items():
    swift += f'''    static let {name} = Color(uiColor: UIColor {{ traits in
        traits.userInterfaceStyle == .dark
            ? UIColor({rgb(resolved('dark',key))}, alpha: 1)
            : UIColor({rgb(resolved('light',key))}, alpha: 1)
    }})
'''
for name,key,style in [('heading','type-h3','title3'),('rowHeading','type-h4','headline'),('body','type-p3','body'),('caption','type-p4','caption'),('label','type-label3','subheadline'),('code','type-mono','body')]:
    match=re.match(r'(\d+) (\d+)px / (\d+)px',tokens['light'][key])
    weight={'400':'regular','500':'medium','600':'semibold'}[match[1]]
    tracking=tokens['light']['tracking-heading'] if name in ['heading','rowHeading'] else tokens['light']['tracking-label'] if name=='label' else '0em'
    swift+=f'    static let {name} = TextStyle(size: {match[2]}, lineHeight: {match[3]}, weight: .{weight}, relativeTo: .{style}, tracking: {float(tracking[:-2])})\n'
swift += f'    static let controlRadius: CGFloat = {tokens["light"]["radius-small"][:-2]}\n'
swift += '''
    struct TextStyle {
        let size: CGFloat
        let lineHeight: CGFloat
        let weight: Font.Weight
        let relativeTo: Font.TextStyle
        let tracking: CGFloat
    }
}

private struct AppearanceText: ViewModifier {
    let style: Appearance.TextStyle
    @ScaledMetric private var size: CGFloat
    @ScaledMetric private var lineSpacing: CGFloat

    init(_ style: Appearance.TextStyle) {
        self.style = style
        _size = ScaledMetric(wrappedValue: style.size, relativeTo: style.relativeTo)
        let naturalHeight = UIFont(name: "DMSans-Regular", size: style.size)?.lineHeight ?? style.size
        _lineSpacing = ScaledMetric(wrappedValue: max(0, style.lineHeight - naturalHeight), relativeTo: style.relativeTo)
    }

    func body(content: Content) -> some View {
        content
            .font(.custom("DMSans-Regular", size: style.size, relativeTo: style.relativeTo).weight(style.weight))
            .lineSpacing(lineSpacing)
            .tracking(size * style.tracking)
    }
}

struct AppearanceButtonStyle: ButtonStyle {
    var prominent = false
    @Environment(\\.isEnabled) private var isEnabled

    func makeBody(configuration: Configuration) -> some View {
        configuration.label
            .appearanceText(Appearance.label)
            .multilineTextAlignment(.center)
            .fixedSize(horizontal: false, vertical: true)
            .padding(.horizontal, 12)
            .padding(.vertical, 8)
            .frame(minWidth: 44, minHeight: 44)
            .foregroundStyle(prominent && isEnabled ? Appearance.onFill : Appearance.primary)
            .background(prominent && isEnabled ? Appearance.brand : Appearance.page,
                        in: RoundedRectangle(cornerRadius: Appearance.controlRadius))
            .overlay(RoundedRectangle(cornerRadius: Appearance.controlRadius)
                .strokeBorder(prominent && isEnabled ? Appearance.brand : Appearance.controlBorder))
            .opacity(configuration.isPressed ? 0.75 : isEnabled ? 1 : 0.6)
            .contentShape(Rectangle())
    }
}

private struct AppearanceMonospaced: ViewModifier {
    @ScaledMetric private var size: CGFloat

    init(_ style: Appearance.TextStyle) {
        _size = ScaledMetric(wrappedValue: style.size, relativeTo: style.relativeTo)
    }

    func body(content: Content) -> some View {
        content.font(.system(size: size, design: .monospaced))
    }
}

extension View {
    func appearanceMono(_ style: Appearance.TextStyle) -> some View {
        modifier(AppearanceMonospaced(style))
    }

    func appearanceText(_ style: Appearance.TextStyle) -> some View {
        modifier(AppearanceText(style))
    }
}
'''

syntax = json.loads((ROOT / 'appearance/syntax.json').read_text())
syntax_ts = '// Generated by appearance/generate.py; edit appearance/syntax.json.\nexport const syntaxColours = {\n'
syntax_swift = '// Generated by appearance/generate.py; edit appearance/syntax.json.\nimport UIKit\n\nenum SyntaxPalette {\n    static func color(_ tag: String, traits: UITraitCollection) -> UIColor? {\n        switch tag {\n'
for tag, (light, dark) in syntax.items():
    syntax_ts += f'  {tag}: ["{light}", "{dark}"],\n'
    syntax_swift += f'        case "{tag}": traits.userInterfaceStyle == .dark ? UIColor({rgb(dark)}, alpha: 1) : UIColor({rgb(light)}, alpha: 1)\n'
syntax_ts += '} satisfies Record<string, [string, string]>;\n'
syntax_swift += '        default: nil\n        }\n    }\n}\n'

parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
for path,content in [('ui/design-system/appearance.css',css),('ios/Appearance/Appearance.swift',swift),('ui/diff-view/syntax-palette.ts',syntax_ts),('ios/CodeStyling/Sources/SyntaxPalette.swift',syntax_swift)]:
    target=ROOT/path
    if args.check:
        if target.read_text()!=content:
            raise SystemExit(f'{path} is stale; run python3 appearance/generate.py')
    else:
        target.write_text(content)
